#!/usr/bin/env python3
"""Generate the Pet / Codex / Sand home icons as LVGL RGB565A8 C arrays.

Uses Pillow (available in the bridge venv). Icons are drawn at 4x and
downsampled, then masked to the same circular 120x120 tile the other Badge
icons use.
"""
import os
from PIL import Image, ImageDraw

N = 120
SS = 4
S = N * SS
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "main", "assets")


def rgb565(p):
    r, g, b = p[0] >> 3, p[1] >> 2, p[2] >> 3
    return (r << 11) | (g << 5) | b


def mask_circle():
    m = Image.new("L", (S, S), 0)
    ImageDraw.Draw(m).ellipse((0, 0, S - 1, S - 1), fill=255)
    return m.resize((N, N), Image.LANCZOS)


def emit(name, im):
    im = im.resize((N, N), Image.LANCZOS).convert("RGBA")
    im.putalpha(mask_circle())
    px = im.load()
    body = bytearray()
    alpha = bytearray()
    for y in range(N):
        for x in range(N):
            p = px[x, y]
            v = rgb565(p)
            body += bytes((v & 0xFF, v >> 8))
            alpha.append(p[3])
    body += alpha
    path = os.path.join(OUT, f"app_icon_{name}.c")
    with open(path, "w") as f:
        f.write('/* Generated by tools/gen_agent_icons.py. */\n#include "lvgl.h"\n\n')
        f.write(f"static const uint8_t app_icon_{name}_map[] = {{\n")
        for i in range(0, len(body), 16):
            f.write("    " + ",".join(f"0x{b:02X}" for b in body[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write(f"const lv_image_dsc_t app_icon_{name} = {{\n")
        f.write("    .header = {\n        .magic = LV_IMAGE_HEADER_MAGIC,\n")
        f.write("        .cf = LV_COLOR_FORMAT_RGB565A8,\n        .flags = 0,\n")
        f.write(f"        .w = {N},\n        .h = {N},\n        .stride = {N * 2},\n")
        f.write("    },\n")
        f.write(f"    .data_size = sizeof(app_icon_{name}_map),\n")
        f.write(f"    .data = app_icon_{name}_map,\n}};\n")
    print("wrote", path)


def pet():
    im = Image.new("RGBA", (S, S), (42, 29, 24, 255))
    d = ImageDraw.Draw(im)
    d.ellipse((18, 18, S - 18, S - 18), outline=(242, 178, 122, 255), width=10)
    # ears
    d.ellipse((118, 120, 205, 220), fill=(246, 215, 176, 255))
    d.ellipse((275, 120, 362, 220), fill=(246, 215, 176, 255))
    # body / head
    d.ellipse((108, 150, 372, 406), fill=(246, 215, 176, 255))
    # eyes
    d.ellipse((178, 245, 214, 281), fill=(45, 33, 28, 255))
    d.ellipse((266, 245, 302, 281), fill=(45, 33, 28, 255))
    # cheeks + mouth
    d.ellipse((156, 300, 190, 322), fill=(232, 138, 106, 180))
    d.ellipse((290, 300, 324, 322), fill=(232, 138, 106, 180))
    d.arc((210, 286, 270, 330), 200, 340, fill=(120, 73, 52, 255), width=7)
    return im


def codex():
    im = Image.new("RGBA", (S, S), (12, 22, 20, 255))
    d = ImageDraw.Draw(im)
    d.ellipse((18, 18, S - 18, S - 18), outline=(34, 211, 166, 255), width=10)
    d.arc((70, 70, S - 70, S - 70), 140, 400, fill=(127, 176, 255, 255), width=14)
    # code chevron + underscore
    d.line((150, 200, 214, 252), fill=(34, 211, 166, 255), width=16, joint="curve")
    d.line((214, 252, 150, 304), fill=(34, 211, 166, 255), width=16, joint="curve")
    d.line((250, 300, 330, 300), fill=(241, 243, 245, 255), width=16)
    d.ellipse((S // 2 - 10, S // 2 - 10, S // 2 + 10, S // 2 + 10), fill=(34, 211, 166, 255))
    return im


def sand():
    im = Image.new("RGBA", (S, S), (21, 16, 11, 255))
    d = ImageDraw.Draw(im)
    # bowl / glass
    d.arc((60, 70, S - 60, S - 40), 20, 160, fill=(224, 192, 128, 255), width=12)
    # sand pile
    d.polygon([(120, 350), (240, 235), (360, 350)], fill=(224, 192, 128, 255))
    d.polygon([(150, 350), (240, 270), (330, 350)], fill=(200, 154, 90, 255))
    # falling grains
    for x, y, r in ((150, 150, 9), (210, 115, 7), (270, 160, 10), (320, 120, 6), (190, 195, 6)):
        d.ellipse((x - r, y - r, x + r, y + r), fill=(240, 214, 158, 255))
    return im


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    emit("pet", pet())
    emit("codex", codex())
    emit("sand", sand())
